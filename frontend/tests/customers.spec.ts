import { test, expect } from './fixtures'
import { execFileSync } from 'node:child_process'

const prefix = `UIT${Date.now()}`
const codes: string[] = []
test.afterAll(() => {
  if (!codes.length) return
  if (!codes.every(code => /^[A-Z0-9]+$/.test(code))) throw new Error('Unsafe test code')
  execFileSync('sqlcmd.exe', ['-S', 'localhost', '-E', '-C', '-d', 'FIN05', '-b', '-Q',
    `DELETE FROM dbo.AuditLogs WHERE EntityName=N'Customers' AND EntityId IN (SELECT CONVERT(nvarchar(64),CustomerId) FROM dbo.Customers WHERE CustomerCode IN (${codes.map(code => `'${code}'`).join(',')})); DELETE FROM dbo.Customers WHERE CustomerCode IN (${codes.map(code => `'${code}'`).join(',')});`])
})

